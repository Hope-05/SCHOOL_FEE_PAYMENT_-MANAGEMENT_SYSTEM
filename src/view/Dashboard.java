    public Dashboard() {
        initComponents();
         // 1. Get the logged-in user
    model.user currentUser = util.SessionManager.getCurrentUser();
    
    // 2. Display their name and role
    if (currentUser != null) {
        jLabel1.setText("Welcome, " + currentUser.getFullName());
        jLabel3.setText("Role: [" + currentUser.getRole() + "]");
        
        // 3. Hide buttons based on role
        String role = currentUser.getRole();
        if (role.equals("VIEWER")) {
            btnManageStudents.setVisible(false);
            btnSetupFees.setVisible(false);
            btnRecordPayment.setVisible(false);
            btnGenerateInvoice.setVisible(false);
        } else if (role.equals("BURSAR")) {
            btnManageStudents.setVisible(false);
            btnSetupFees.setVisible(false);
            btnGenerateInvoice.setVisible(false);
        }
    }
    }

