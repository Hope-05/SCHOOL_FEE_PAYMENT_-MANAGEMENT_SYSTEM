    private void btnSaveStudentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveStudentActionPerformed
        // TODO add your handling code here:
    String fullName = txtFullName.getText().trim();
    String classLevel = (String) cmbClassLevel.getSelectedItem();
    String guardianContact = txtGuardianContact.getText().trim();

    if (fullName.isEmpty() || guardianContact.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please fill in all fields.");
        return;
    }

    model.student newStudent = new model.student();
    newStudent.setFullName(fullName);
    newStudent.setClassLevel(classLevel);
    newStudent.setGuardianContact(guardianContact);
    newStudent.setStatus("ACTIVE"); // Automatically ACTIVE

    dao.StudentDao studentDao = new dao.StudentDao();
    studentDao.save(newStudent);

    javax.swing.JOptionPane.showMessageDialog(this, "Student registered successfully!");
    
    txtFullName.setText("");
    txtGuardianContact.setText("");
    cmbClassLevel.setSelectedIndex(0);
    
    loadStudentData();      
    }//GEN-LAST:event_btnSaveStudentActionPerformed

    private void btnUpdateStudentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateStudentActionPerformed
        // TODO add your handling code here:
     int selectedRow = tblStudents.getSelectedRow();
    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a student from the table.");
        return;
    }

    Long studentId = (Long) tblStudents.getValueAt(selectedRow, 0);
    String fullName = txtFullName.getText().trim();
    String classLevel = (String) cmbClassLevel.getSelectedItem();
    String guardianContact = txtGuardianContact.getText().trim();

    if (fullName.isEmpty() || guardianContact.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Fields cannot be empty.");
        return;
    }

    dao.StudentDao studentDao = new dao.StudentDao();
    model.student existingStudent = studentDao.findById(studentId);
    
    if (existingStudent != null) {
        existingStudent.setFullName(fullName);
        existingStudent.setClassLevel(classLevel);
        existingStudent.setGuardianContact(guardianContact);
        // Status remains whatever it currently is
        
        studentDao.update(existingStudent);
        javax.swing.JOptionPane.showMessageDialog(this, "Student updated successfully!");
        loadStudentData(); 
    }    
    }//GEN-LAST:event_btnUpdateStudentActionPerformed

    private void btnDeleteStudentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteStudentActionPerformed
        // TODO add your handling code here:
     int selectedRow = tblStudents.getSelectedRow();
    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a student from the table to delete.");
        return;
    }

    int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Delete this student permanently?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
    
    if (confirm == javax.swing.JOptionPane.YES_OPTION) {
        // Read the ID as a String, then convert to Long
        String idStr = tblStudents.getValueAt(selectedRow, 0).toString();
        Long studentId = Long.parseLong(idStr);
        
        dao.StudentDao studentDao = new dao.StudentDao();
        model.student s = studentDao.findById(studentId);
        
        if (s != null) {
            try {
                // Try to delete the student
                studentDao.delete(s);
                javax.swing.JOptionPane.showMessageDialog(this, "Student deleted permanently.");
                loadStudentData(); 
                
            } catch (Exception e) {
                // THIS IS WHERE OPTION 2 GOES!
                // If the database throws a Foreign Key error, we catch it here.
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "Cannot delete this student because they have invoices or payments attached to them.\nPlease use the DEACTIVATE button instead.", 
                    "Delete Failed", 
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }
    }//GEN-LAST:event_btnDeleteStudentActionPerformed

    private void btnDeactivateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeactivateActionPerformed
        // TODO add your handling code here:
    int selectedRow = tblStudents.getSelectedRow();
    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a student from the table.");
        return;
    }

    Long studentId = (Long) tblStudents.getValueAt(selectedRow, 0);
    
    dao.StudentDao studentDao = new dao.StudentDao();
    model.student s = studentDao.findById(studentId);
    
    if (s != null) {
        s.setStatus("INACTIVE");
        studentDao.update(s);
        javax.swing.JOptionPane.showMessageDialog(this, "Student marked as INACTIVE.");
        loadStudentData(); 
    }    
    }//GEN-LAST:event_btnDeactivateActionPerformed

