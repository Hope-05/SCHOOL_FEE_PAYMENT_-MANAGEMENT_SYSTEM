    private void loadStudentData() {
    // Get the table model
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblStudents.getModel();
    
    // Clear existing rows
    model.setRowCount(0);
    
    // Fetch from database
    dao.StudentDao studentDao = new dao.StudentDao();
    java.util.List<model.student> studentList = studentDao.findAll();
    
    // Loop through the list and add rows
    for (model.student s : studentList) {
        Object[] row = {
            s.getId(),
            s.getFullName(),
            s.getClassLevel(),
            s.getGuardianContact(),
            s.getStatus()
        };
        model.addRow(row);
    }
}

